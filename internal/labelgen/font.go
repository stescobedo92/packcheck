// glyphs pre-parsed: [7]uint8 with bit 4 as the leftmost column.
var glyphs = parseGlyphs()

func parseGlyphs() map[rune][7]uint8 {
	out := make(map[rune][7]uint8, len(glyphRows))
	for r, rows := range glyphRows {
		parts := strings.Split(rows, "/")
		if len(parts) != 7 {
			continue // constant data; tests verify glyph coverage
		}
		var g [7]uint8
		for i, row := range parts {
			for col := 0; col < 5 && col < len(row); col++ {
				if row[col] == '1' {
					g[i] |= 1 << uint(4-col)
				}
			}
		}
		out[r] = g
	}
	return out
}

const (
	glyphW = 5
	glyphH = 7
)

// HasGlyph reports whether the font can print the character.
func HasGlyph(r rune) bool {
	_, ok := glyphs[r]
	return ok
}

// printable converts text to its printable form: uppercase without accents;
// any character without a glyph becomes a space (never an invented glyph).
func printable(s string) string {
	s = strings.ToUpper(foldForPrint(s))
	return strings.Map(func(r rune) rune {
		if HasGlyph(r) {
			return r
		}
		return ' '
	}, s)
}

var printFold = map[rune]rune{
	'Á': 'A', 'É': 'E', 'Í': 'I', 'Ó': 'O', 'Ú': 'U', 'Ü': 'U', 'Ñ': 'N',
	'á': 'a', 'é': 'e', 'í': 'i', 'ó': 'o', 'ú': 'u', 'ü': 'u', 'ñ': 'n',
}

func foldForPrint(s string) string {
	return strings.Map(func(r rune) rune {
		if f, ok := printFold[r]; ok {
			return f
		}
		return r
	}, s)
}
